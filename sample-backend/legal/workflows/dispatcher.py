from typing import Protocol
from uuid import UUID


class WorkflowDispatcher(Protocol):
    def dispatch(self, command_id: UUID) -> None: ...


class WorkflowExecutionBackend(Protocol):
    def start(self, command_id: UUID) -> None: ...

    def signal(self, command_id: UUID) -> None: ...

    def cancel(self, command_id: UUID) -> None: ...

    def inspect(self, command_id: UUID) -> dict: ...
